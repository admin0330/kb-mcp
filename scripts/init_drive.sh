#!/usr/bin/env bash
#
# init_drive.sh — initialise the knowledge-base directory structure on an
# external APFS volume. Idempotent: safe to run repeatedly. Logs everything to
# <volume>/.mcp_meta/init.log as well as stdout.
#
# Usage:
#   ./init_drive.sh [/Volumes/KnowledgeBase]
#
set -euo pipefail

VOLUME="${1:-/Volumes/KnowledgeBase}"
META_DIR="${VOLUME}/.mcp_meta"
INDEX_FILE="${VOLUME}/INDEX.md"
LOG_FILE="${META_DIR}/init.log"

# Colours (fall back to empty when not a tty).
if [[ -t 1 ]]; then
  R=$'\033[31m'; G=$'\033[32m'; Y=$'\033[33m'; B=$'\033[34m'; N=$'\033[0m'
else
  R=""; G=""; Y=""; B=""; N=""
fi

log()  { printf '%s[%s] %s%s\n' "$B" "$(date '+%Y-%m-%d %H:%M:%S')" "$1" "$N"; }
ok()   { printf '%s  ✓ %s%s\n' "$G" "$1" "$N"; }
warn() { printf '%s  ! %s%s\n' "$Y" "$1" "$N"; }
die()  { printf '%s  ✗ %s%s\n' "$R" "$1" "$N" >&2; exit 1; }

# --- 1. verify mount point ------------------------------------------------- #
log "Initialising knowledge base at: ${VOLUME}"
[[ -d "$VOLUME" ]] || die "Volume not found: ${VOLUME} (is the drive plugged in?)"
[[ -w "$VOLUME" ]] || die "Volume not writable: ${VOLUME} (check permissions)"
ok "Mount point exists and is writable"

# --- 2. verify filesystem is APFS (warn only) ------------------------------ #
FS_TYPE="$(diskutil info "$VOLUME" 2>/dev/null | awk -F': *' '/File System Personality/{print $2}' || true)"
if [[ -n "$FS_TYPE" ]]; then
  if [[ "$FS_TYPE" == *APFS* ]]; then
    ok "Filesystem: ${FS_TYPE}"
  else
    warn "Filesystem is '${FS_TYPE}', not APFS — the tooling still works, "
    warn "but APFS is recommended for snapshots & space sharing."
  fi
else
  warn "Could not determine filesystem type (diskutil unavailable); continuing."
fi

# --- 3. create directory structure ----------------------------------------- #
DIRS=("_Inbox" "01_Documents" "02_Books" "03_Notes" "04_Archive" ".mcp_meta")
created=0
for d in "${DIRS[@]}"; do
  target="${VOLUME}/${d}"
  if [[ -d "$target" ]]; then
    ok "exists: ${d}/"
  else
    mkdir -p "$target"
    ok "created: ${d}/"
    created=$((created + 1))
  fi
done

# Start logging to the drive now that .mcp_meta exists.
{
  echo "[$(date '+%Y-%m-%d %H:%M:%S')] init_drive.sh run (created ${created} new dirs)"
} >> "$LOG_FILE"

# --- 4. seed INDEX.md -------------------------------------------------------- #
if [[ -f "$INDEX_FILE" ]]; then
  ok "INDEX.md already present (left untouched)"
else
  cat > "$INDEX_FILE" <<EOF
# 📚 KnowledgeBase Index

> This file is the auto-maintained table of contents for the knowledge base.
> It is regenerated by the \`kb_update_index_md\` MCP tool after each organise run.
> First generated: $(date '+%Y-%m-%d %H:%M').

## _Inbox  —  待整理缓冲区 (triage buffer)  (0)
- _(empty)_

## 01_Documents  —  通用文档、报告 (documents & reports)  (0)
- _(empty)_

## 02_Books  —  电子书、手册 (books & manuals)  (0)
- _(empty)_

## 03_Notes  —  个人笔记、卡片 (notes & cards)  (0)
- _(empty)_

## 04_Archive  —  历史归档 (archive)  (0)
- _(empty)_
EOF
  ok "created: INDEX.md"
fi

# --- 5. drop a root marker (used for sanity checks) ------------------------- #
MARKER="${META_DIR}/.kb_root"
if [[ ! -f "$MARKER" ]]; then
  cat > "$MARKER" <<EOF
schema=1
created=$(date '+%Y-%m-%dT%H:%M:%S')
volume=${VOLUME}
EOF
  ok "created: .mcp_meta/.kb_root marker"
fi

log "Done. Structure ready at ${VOLUME}"
printf '%s\n' "  Next: index the drive from Claude via the kb_reindex tool, or run the setup script."
